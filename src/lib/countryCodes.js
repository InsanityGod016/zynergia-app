function isoFromFlag(flag) {
  const letters = Array.from(flag || '').map(symbol => symbol.codePointAt(0) - 127397);
  if (letters.length !== 2 || letters.some(value => value < 65 || value > 90)) return null;
  return String.fromCharCode(...letters);
}

